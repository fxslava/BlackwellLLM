// ---- shared test body --------------------------------------------------------

class TokenizerGolden : public ::testing::TestWithParam<const char*> {
protected:
    void SetUp() override {
        const std::string dir = GetParam() == std::string("llama3") ? llama_dir() : qwen_dir();
        if (!has_tokenizer(dir))
            GTEST_SKIP() << "tokenizer.json not found under " << dir
                         << " (set BLACKWELL_LLAMA_DIR / BLACKWELL_QWEN_DIR to override)";
        tokenizer_ = TokenizerFactory::create(dir);
    }

    const GoldenEncodeCase* cases() const {
        return GetParam() == std::string("llama3") ? k_llama3_encode_cases
                                                   : k_qwen25_encode_cases;
    }
    size_t case_count() const {
        return GetParam() == std::string("llama3")
                   ? std::size(k_llama3_encode_cases)
                   : std::size(k_qwen25_encode_cases);
    }

    std::unique_ptr<ITokenizer> tokenizer_;
};

TEST_P(TokenizerGolden, EncodeMatchesHuggingFace) {
    for (size_t i = 0; i < case_count(); ++i) {
        const auto& c = cases()[i];
        EXPECT_EQ(tokenizer_->encode(c.text, false), c.plain) << "text: " << c.text;
        EXPECT_EQ(tokenizer_->encode(c.text, true), c.with_special)
            << "text (with specials): " << c.text;
    }
}

TEST_P(TokenizerGolden, DecodeRoundTripsExactly) {
    // Byte-level BPE is lossless: decode(encode(x)) must reproduce x byte-for-byte.
    for (size_t i = 0; i < case_count(); ++i) {
        const auto& c = cases()[i];
        EXPECT_EQ(tokenizer_->decode(tokenizer_->encode(c.text, false)), c.text);
    }
}

TEST_P(TokenizerGolden, ChatTemplateMatchesHuggingFace) {
    ASSERT_NE(tokenizer_->chat_template(), nullptr);
    const bool is_llama = GetParam() == std::string("llama3");
    EXPECT_EQ(tokenizer_->apply_chat_template(k_chat, true),
              is_llama ? k_llama3_chat_ids : k_qwen25_chat_ids);
    // No system message: Llama-3 still emits its dated system block, ChatML
    // injects the default prompt extracted from the Jinja source.
    EXPECT_EQ(tokenizer_->apply_chat_template(k_chat_nosys, true),
              is_llama ? k_llama3_chat_nosys_ids : k_qwen25_chat_nosys_ids);
}

TEST_P(TokenizerGolden, IncrementalChatApiComposesToFullConversation) {
    std::vector<int> ids = tokenizer_->encode_chat_prelude(k_chat[0].content);
    for (size_t i = 1; i < k_chat.size(); ++i) {
        const auto turn = tokenizer_->encode_chat_message(k_chat[i]);
        ids.insert(ids.end(), turn.begin(), turn.end());
    }
    const auto gen = tokenizer_->encode_generation_prompt();
    ids.insert(ids.end(), gen.begin(), gen.end());
    EXPECT_EQ(ids, tokenizer_->apply_chat_template(k_chat, true));
}

