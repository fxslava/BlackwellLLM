std::string env_or(const char* name, const char* fallback) {
    const char* v = std::getenv(name);
    return v && *v ? v : fallback;
}

std::string llama_dir() { return env_or("BLACKWELL_LLAMA_DIR", "F:/AI/llama3-8b-fp8"); }
std::string qwen_dir() {
    return env_or("BLACKWELL_QWEN_DIR", "F:/AI/Qwen2.5-Coder-7B-Instruct-AWQ");
}

bool has_tokenizer(const std::string& dir) {
    return std::filesystem::exists(std::filesystem::path(dir) / "tokenizer.json");
}

