// ---- per-model special-token resolution -------------------------------------

TEST(TokenizerGoldenLlama, SpecialTokensResolvedFromConfigs) {
    if (!has_tokenizer(llama_dir())) GTEST_SKIP() << "Llama checkpoint not present";
    const auto tok = TokenizerFactory::create(llama_dir());

    const auto& st = tok->special_tokens();
    EXPECT_EQ(st.bos, tok->token_to_id("<|begin_of_text|>"));
    EXPECT_EQ(st.eos, tok->token_to_id("<|eot_id|>"));
    // config.json eos_token_id list = {end_of_text, eom_id, eot_id}.
    EXPECT_EQ(st.stop_ids.size(), 3u);
    for (const int id : st.stop_ids) EXPECT_TRUE(tok->is_special(id));
    EXPECT_TRUE(tok->is_stop(st.eos));

    // BOS comes from the post-processor when add_special_tokens=true.
    const auto ids = tok->encode("hi", true);
    ASSERT_FALSE(ids.empty());
    EXPECT_EQ(ids.front(), st.bos);
    EXPECT_EQ(tok->decode(st.bos), "");
    EXPECT_EQ(tok->decode(st.bos, true), "<|begin_of_text|>");
}

TEST(TokenizerGoldenQwen, SpecialTokensResolvedFromConfigs) {
    if (!has_tokenizer(qwen_dir())) GTEST_SKIP() << "Qwen checkpoint not present";
    const auto tok = TokenizerFactory::create(qwen_dir());

    const auto& st = tok->special_tokens();
    // tokenizer_config.json says bos_token: null, but config.json still
    // declares bos_token_id (= <|endoftext|>); the factory falls back to it.
    // What matters is that no BOS is ever *injected* (asserted below).
    EXPECT_EQ(st.bos, tok->token_to_id("<|endoftext|>"));
    EXPECT_EQ(st.eos, tok->token_to_id("<|im_end|>"));
    // generation_config.json stop set: {<|im_end|>, <|endoftext|>}.
    EXPECT_EQ(st.stop_ids.size(), 2u);
    EXPECT_TRUE(tok->is_stop(tok->token_to_id("<|im_end|>")));
    EXPECT_TRUE(tok->is_stop(tok->token_to_id("<|endoftext|>")));

    // No post-processor inserts: add_special_tokens is a no-op.
    EXPECT_EQ(tok->encode("hi", true), tok->encode("hi", false));

    // Special-token strings in raw text resolve to their ids.
    const auto ids = tok->encode("<|im_start|>user\nhi<|im_end|>", false);
    ASSERT_GE(ids.size(), 2u);
    EXPECT_EQ(ids.front(), tok->token_to_id("<|im_start|>"));
    EXPECT_EQ(ids.back(), tok->token_to_id("<|im_end|>"));
}

